def fiche_routeur(peripherique, fabricant, modele, num_modele, serie, identifiant):
    print("===========================\n"
        "--- FICHE DU ROUTEUR ---\n"
          "============================")
    print(f"Périphérique : {peripherique}")
    print(f"Fabricant    : {fabricant}")
    print(f"Modèle       : {modele} (N° {num_modele})")
    print(f"N° de série  : {serie}")
    print(f"ID Unique    : {identifiant}")